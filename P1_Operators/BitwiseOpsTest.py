#Bitwise operators are used to compare (binary) numbers:
x = 5  # Binary: 101
y = 3  # Binary: 011
print("x & y:", x & y)  # AND
print("x | y:", x | y)  # OR
print("x ^ y:", x ^ y)  # XOR
print("~x:", ~x)        # NOT
print("x << 1:", x << 1)  # Left shift
print("x >> 1:", x >> 1)  # Right shift

